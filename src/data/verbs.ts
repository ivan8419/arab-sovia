const madhiEndings: Record<Dhomir, string> = {
  huwa: 'َ',
  huma_m: 'ا',
  hum: 'وا',
  hiya: 'تْ',
  huma_f: 'تَا',
  hunna: 'نَ',
  anta: 'تَ',
  antuma_m: 'تُمَا',
  antum: 'تُمْ',
  anti: 'تِ',
  antuma_f: 'تُمَا',
  antunna: 'تُنَّ',
  ana: 'تُ',
  nahnu: 'نَا',
}

const mudhariForms: Record<Dhomir, (stem: string) => string> = {
  huwa: (stem) => `يَ${stem}ُ`,
  huma_m: (stem) => `يَ${stem}َانِ`,
  hum: (stem) => `يَ${stem}ُونَ`,
  hiya: (stem) => `تَ${stem}ُ`,
  huma_f: (stem) => `تَ${stem}َانِ`,
  hunna: (stem) => `يَ${stem}ْنَ`,
  anta: (stem) => `تَ${stem}ُ`,
  antuma_m: (stem) => `تَ${stem}َانِ`,
  antum: (stem) => `تَ${stem}ُونَ`,
  anti: (stem) => `تَ${stem}ِينَ`,
  antuma_f: (stem) => `تَ${stem}َانِ`,
  antunna: (stem) => `تَ${stem}ْنَ`,
  ana: (stem) => `أَ${stem}ُ`,
  nahnu: (stem) => `نَ${stem}ُ`,
}

const amrForms: Partial<Record<Dhomir, (stem: string) => string>> = {
  anta: (stem) => `ا${stem}`,
  antuma_m: (stem) => `ا${stem}ا`,
  antum: (stem) => `ا${stem}وا`,
  anti: (stem) => `ا${stem}ي`,
  antuma_f: (stem) => `ا${stem}ا`,
  antunna: (stem) => `ا${stem}نَ`,
}

function buildConjugations(seed: VerbSeed): Conjugation[] {
  return dhomirList.map(({ dhomir, label }) => ({
    dhomir,
    dhomirLabel: label,
    madhi: `${seed.madhiStem}${madhiEndings[dhomir]}`,
    mudhari: mudhariForms[dhomir](seed.presentStem),
    amr: amrForms[dhomir]?.(seed.amrStem),
  }))
}

function createVerb(seed: VerbSeed): Fiil {
  const conjugations = buildConjugations(seed)

  return {
    id: seed.id,
    root: seed.root,
    madhi: conjugations[0].madhi,
    mudhari: conjugations[0].mudhari,
    amr: conjugations[6].amr ?? `ا${seed.amrStem}`,
    mashdar: seed.mashdar,
    meaning: seed.meaning,
    type: seed.type,
    difficulty: seed.difficulty,
    audioPath: `/audio/verbs/${seed.id}.mp3`,
    audioExample: `/audio/examples/${seed.id}.mp3`,
    conjugations,
  }
}

