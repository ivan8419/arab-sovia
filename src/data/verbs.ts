export const verbsData: Fiil[] = verbSeeds.map(createVerb)

export function getVerbById(id: string): Fiil | undefined {
  return verbsData.find((verb) => verb.id === id)
}

export function searchVerbs(query: string): Fiil[] {
  const normalizedQuery = normalizeArabicText(query).toLowerCase()

  return verbsData.filter((verb) => {
    const searchable = [
      verb.meaning.toLowerCase(),
      normalizeArabicText(verb.madhi).toLowerCase(),
      normalizeArabicText(verb.mudhari).toLowerCase(),
      verb.root.toLowerCase(),
      verb.root.replace(/-/g, ' ').toLowerCase(),
    ]

    return searchable.some((item) => item.includes(normalizedQuery))
  })
}

export function filterVerbs(options: {
  difficulty?: Difficulty
  type?: VerbType
}): Fiil[] {
  return verbsData.filter((verb) => {
    if (options.difficulty && verb.difficulty !== options.difficulty) {
      return false
    }

    if (options.type && verb.type !== options.type) {
      return false
    }

    return true
  })
}

export function getRandomVerbs(count: number): Fiil[] {
  return [...verbsData].sort(() => Math.random() - 0.5).slice(0, count)
}

export function getVerbsByDifficulty(difficulty: Difficulty): Fiil[] {
  return verbsData.filter((verb) => verb.difficulty === difficulty)
}
